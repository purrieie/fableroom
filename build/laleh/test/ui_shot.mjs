// UI states on the harness page.  node test/ui_shot.mjs <outdir> <w> <h> [dpr]
import puppeteer from 'puppeteer-core';
import fs from 'fs';
const [,, out, W = '390', H = '664', DPR = '3'] = process.argv;
fs.mkdirSync(out, { recursive: true });
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--no-sandbox', '--use-angle=metal', '--hide-scrollbars'] });
const page = await b.newPage(), errs = [];
page.on('pageerror', e => errs.push(String(e).slice(0, 300)));
page.on('console', m => { if (m.type() === 'error') errs.push(m.text().slice(0, 200)); });
const mobile = +W < 700;
await page.setViewport({ width: +W, height: +H, deviceScaleFactor: +DPR, isMobile: mobile, hasTouch: mobile });
if (process.env.SCENES) await page.evaluateOnNewDocument(s => { window.__scenes = JSON.parse(s); }, fs.readFileSync(process.env.SCENES, 'utf8'));
await page.goto('http://localhost:8812/build/laleh/test/harness.html', { waitUntil: 'load' });
const wait = ms => new Promise(r => setTimeout(r, ms));
const shot = n => page.screenshot({ path: `${out}/${n}.png` });
await page.evaluate(() => window.FRRV.open('room', 'test'));
await page.waitForFunction(() => document.querySelector('.frrv-stage.is-ready'), { timeout: 20000 });
await wait(900); await shot('01-room');
await page.click('[data-act=cmp]'); await wait(500); await shot('02-compare');
await page.click('[data-act=cmp]'); await page.click('[data-act=ba]'); await wait(500); await shot('03-before-after');
await page.click('[data-act=ba]'); await page.click('[data-act=zoom]'); await wait(500); await shot('04-zoom');
await page.click('[data-act=zoom]');
await page.evaluate(() => { const r = document.querySelector('.frrv-rotbar input'); r.value = 35; r.dispatchEvent(new Event('input')); }); await wait(300); await shot('05-rotated');
await page.click('[data-act=full]'); await wait(500); await shot('06-full'); await page.click('[data-act=full]'); await wait(300);
await page.click('.frrv-tabs [data-t=size]'); await wait(400); await shot('07-size-living');
const sz = await page.evaluate(() => { const p = document.querySelector('.frrv-pane[data-p=size]'); return { scroll: p.scrollHeight, client: p.clientHeight }; });
await page.click('.frrv-seg[data-k=room] [data-v=bedroom]'); await wait(300); await shot('08-size-bedroom');
await page.click('.frrv-seg[data-k=room] [data-v=dining]'); await wait(300); await shot('09-size-dining');
const sz2 = await page.evaluate(() => { const p = document.querySelector('.frrv-pane[data-p=size]'); return { scroll: p.scrollHeight, client: p.clientHeight }; });
console.log(JSON.stringify({ sizePaneLiving: sz, sizePaneDining: sz2, errors: errs.slice(0, 8) }));
await b.close(); process.exit(0);
